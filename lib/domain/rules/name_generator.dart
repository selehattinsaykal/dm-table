/// [count] adet isim uretir.
///
/// [turkish] kalip adlari (meyhane/lonca/tapinak/eser...) Turkce uretir; kisi
/// ve yer adlari fantastik kokenlidir, cevrilmez. [gender] yalnizca kisi
/// kulturlerinde ve [NameCultureInfo.hasGender] dogruysa etkilidir.
/// [surname] kisi adlarina soyad/lakap ekler. [rng] verilirse sonuc
/// deterministiktir.
List<String> generateNames(
  NameCulture culture, {
  int count = 10,
  bool turkish = false,
  NameGender gender = NameGender.any,
  bool surname = false,
  Random? rng,
}) {
  final random = rng ?? Random();
  final n = count < 1 ? 1 : count;

  // Tekrar etmesin diye kume; cok denemeden sonra biten havuzda takilmamak
  // icin deneme siniri var.
  final out = <String>{};
  for (var attempt = 0; attempt < n * 20 && out.length < n; attempt++) {
    out.add(
      generateName(
        culture,
        turkish: turkish,
        gender: gender,
        surname: surname,
        rng: random,
      ),
    );
  }
  return out.toList();
}

/// Tek bir isim uretir (bkz. [generateNames]).
String generateName(
  NameCulture culture, {
  bool turkish = false,
  NameGender gender = NameGender.any,
  bool surname = false,
  Random? rng,
}) {
  final random = rng ?? Random();

  final phrase = _phrases[culture];
  if (phrase != null) return _fromPhrase(phrase, random, turkish);

  final compound = _compounds[culture];
  if (compound != null) return _fromCompound(compound, random);

  final person = _persons[culture]!;
  final given = _fromPerson(person, random, gender);
  if (!surname || person.surB.isEmpty) return given;
  return '$given ${_surnameOf(person, random)}';
}

String _pick(List<String> list, Random rng) => list[rng.nextInt(list.length)];

String _fromPhrase(_Phrase phrase, Random rng, bool turkish) {
  final a = _pick(turkish ? phrase.aTr : phrase.aEn, rng);
  final b = _pick(turkish ? phrase.bTr : phrase.bEn, rng);
  return (turkish ? phrase.tr : phrase.en)
      .replaceAll('{a}', a)
      .replaceAll('{b}', b);
}

String _fromCompound(_Compound pool, Random rng) {
  final start = _pick(pool.start, rng);
  final end = _pick(pool.end, rng);
  final middle = rng.nextBool() ? _pick(pool.middle, rng) : '';
  return '$start$middle$end';
}

String _fromPerson(_Person pool, Random rng, NameGender gender) {
  final start = _pick(pool.start, rng);
  final end = switch (gender) {
    NameGender.male => _pick(pool.endM, rng),
    NameGender.female => _pick(pool.endF.isEmpty ? pool.endM : pool.endF, rng),
    NameGender.any => _pick(
      pool.endF.isEmpty ? pool.endM : [...pool.endM, ...pool.endF],
      rng,
    ),
  };
  // Orta hece %50 ihtimalle; hep eklenirse isimler tekduze uzuyor.
  final middle = rng.nextBool() ? _pick(pool.middle, rng) : '';
  return '$start$middle$end';
}

String _surnameOf(_Person pool, Random rng) {
  final a = pool.surA.isEmpty ? '' : _pick(pool.surA, rng);
  var b = _pick(pool.surB, rng);
  // "Barrelbarrel" gibi kendini tekrar eden soyadlari ele; birkac deneme
  // yeter, havuzlar kucuk oldugu icin sonsuz donguye girmemeli.
  for (var i = 0; i < 5 && a.toLowerCase() == b.toLowerCase(); i++) {
    b = _pick(pool.surB, rng);
  }
  final joined = a.isEmpty ? b : '$a${pool.surJoin}$b';
  return '${pool.surPrefix}$joined';
}
