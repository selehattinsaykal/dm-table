  epithet,
}

/// Kisi adlarinda kullanilacak cinsiyet tercihi.
enum NameGender { any, male, female }

extension NameCultureInfo on NameCulture {
  NameCategory get category => switch (this) {
    NameCulture.human ||
    NameCulture.humanNorth ||
    NameCulture.humanDesert ||
    NameCulture.humanEast ||
    NameCulture.elf ||
    NameCulture.drow ||
    NameCulture.dwarf ||
    NameCulture.halfling ||
    NameCulture.gnome ||
    NameCulture.orc ||
    NameCulture.goblin ||
    NameCulture.tiefling ||
    NameCulture.dragonborn ||
    NameCulture.goliath ||
    NameCulture.lizardfolk ||
    NameCulture.tabaxi ||
    NameCulture.celestial ||
    NameCulture.undead => NameCategory.person,
    NameCulture.place ||
    NameCulture.city ||
    NameCulture.fortress ||
    NameCulture.ruin ||
    NameCulture.forest ||
    NameCulture.mountain ||
    NameCulture.water ||
    NameCulture.island ||
    NameCulture.region => NameCategory.place,
    NameCulture.tavern ||
    NameCulture.shop ||
    NameCulture.temple => NameCategory.establishment,
    NameCulture.guild ||
    NameCulture.nobleHouse ||
    NameCulture.mercenary ||
    NameCulture.cult => NameCategory.group,
    NameCulture.ship ||
    NameCulture.magicItem ||
    NameCulture.tome ||
    NameCulture.festival ||
    NameCulture.epithet => NameCategory.thing,
  };

  /// Kisi adi mi (cinsiyet/soyad secenekleri ve "NPC olarak kaydet" bunlara ozel).
  bool get isPerson => category == NameCategory.person;

  /// Cinsiyete gore ayri son hece havuzu var mi.
  bool get hasGender {
    final pool = _persons[this];
    return pool != null && pool.endF.isNotEmpty;
  }

  /// Soyad/lakap eklenebilir mi.
  bool get hasSurname => _persons[this]?.surB.isNotEmpty ?? false;
}

