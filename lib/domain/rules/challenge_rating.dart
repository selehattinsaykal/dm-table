/// CR degerleri veride ondalik gelir (0.125) ama masada kesir okunur (1/8).
String formatCr(double cr) => switch (cr) {
  0 => '0',
  0.125 => '1/8',
  0.25 => '1/4',
  0.5 => '1/2',
  _ when cr == cr.roundToDouble() => '${cr.toInt()}',
  _ => '$cr',
};

