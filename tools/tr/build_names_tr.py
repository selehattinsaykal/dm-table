def class_feature_names():
    """Paketteki butun yetenek adlari icin ceviri haritasi.

    Kalip tasiyan adlar ("Bard Spell List", "Core Monk Traits") uretiliyor:
    sinif/alt sinif adi Ingilizce kaliyor, kalibi Turkceleniyor. Kalibi
    olmayan ve [CLASS_FEATURES] icinde de bulunmayan adlar -- alt sinif ozel
    adlari -- disarida birakiliyor, ekranda Ingilizce gorunurler.
    """
    bundle = json.load(
        gzip.open('assets/data/classes.json.gz', 'rt', encoding='utf-8')
    )
    # "<Alt sinif> Spells" alt sinifin buyu listesi; ayni kalibi tasiyan gercek
    # yetenekler ("Absorb Spells", "Sculpt Spells") var, o yuzden kalip
    # yalnizca onek GERCEKTEN bir alt sinif adiysa uygulaniyor.
    subclasses = {row['name'] for row in bundle if row.get('subclass_of')}
    out = {}
    for row in bundle:
        for feature in row.get('features') or []:
            if feature.get('feature_type') not in (
                'CLASS_LEVEL_FEATURE',
                'CORE_TRAITS_TABLE',
            ):
                continue
            name = feature['name']
            if name in out:
                continue
            if name in CLASS_FEATURES:
                out[name] = CLASS_FEATURES[name]
            elif name.endswith(' Spell List'):
                out[name] = f'{name[: -len(" Spell List")]} Büyü Listesi'
            elif name.endswith(' Spells') and name[: -len(' Spells')] in subclasses:
                out[name] = f'{name[: -len(" Spells")]} Büyüleri'
            elif name.endswith(' Subclasses'):
                out[name] = f'{name[: -len(" Subclasses")]} Alt Sınıfları'
            elif name.endswith(' Subclass'):
                out[name] = f'{name[: -len(" Subclass")]} Alt Sınıfı'
            elif name.startswith('Core ') and name.endswith(' Traits'):
                middle = name[len('Core ') : -len(' Traits')]
                out[name] = f'Temel {middle} Özellikleri'
    return dict(sorted(out.items()))


