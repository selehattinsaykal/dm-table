def sub_record_names(kind, section, table):
    """Bir kaydin alt kayit ADLARI ({kind}/{section}) icin ceviri haritasi."""
    bundle = json.load(
        gzip.open(f'assets/data/{kind}.json.gz', 'rt', encoding='utf-8')
    )
    out = {}
    for row in bundle:
        for entry in row.get(section) or []:
            if not isinstance(entry, dict):
                continue
            name = (entry.get('name') or '').strip()
            if name in table:
                out[name] = table[name]
    return dict(sorted(out.items()))


